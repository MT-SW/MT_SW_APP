@file:Suppress("MagicNumber")

package org.meshtastic.feature.discovery.export

private const val PAGE_WIDTH = 612
private const val PAGE_HEIGHT = 792
private const val MARGIN_LEFT = 40f
private const val MARGIN_TOP = 50f
private const val LINE_HEIGHT = 18f
private const val SECTION_GAP = 12f
private const val TITLE_SIZE = 18f
private const val HEADING_SIZE = 14f
private const val BODY_SIZE = 10f
private const val LABEL_SIZE = 9f
private const val FOOTER_SIZE = 8f
private const val PAGE_BOTTOM_MARGIN = 60f
private const val LABEL_COLUMN_WIDTH = 160f

/** Average width of a Helvetica letter, as a share of its size (enough to wrap the text of the report). */
private const val AVERAGE_CHAR_WIDTH = 0.52f

/**
 * The report as a PDF on iPhone/iPad and on the computer (Android draws it with the system's own PDF writer). Written in
 * plain Kotlin with the standard Helvetica fonts, so it needs no library: letters outside Western European are written
 * without their accents (for example Polish "ł" becomes "l") and symbols the font has not got become "?".
 */
class SimplePdfDiscoveryExporter : DiscoveryExporter {
    @Suppress("TooGenericExceptionCaught")
    override suspend fun export(data: DiscoveryExportData): ExportResult = try {
        ExportResult.Success(
            content = render(data),
            mimeType = "application/pdf",
            fileName = DiscoveryReportFormatter.generateFileName(data.session, "pdf"),
        )
    } catch (e: Exception) {
        ExportResult.Error("PDF generation failed: ${e.message}")
    }

    private fun render(data: DiscoveryExportData): ByteArray {
        val page = PdfPages()
        page.title("Discovery Report")
        page.advanceLine()
        page.heading("Session Overview")
        for ((label, value) in DiscoveryReportFormatter.formatSessionOverviewLines(data.session)) {
            page.labelValue(label, value)
        }
        page.advanceSection()
        for (result in data.presetResults) {
            page.heading("Preset: ${result.presetName}")
            for ((label, value) in DiscoveryReportFormatter.formatPresetLines(result)) page.labelValue(label, value)
            val nodes = data.nodesByPreset[result.id].orEmpty()
            if (nodes.isNotEmpty()) {
                page.advanceLine()
                page.subheading("Discovered Nodes (${nodes.size})")
                for (node in nodes) page.body(DiscoveryReportFormatter.formatNodeLine(node, data.measurementSystem))
            }
            page.advanceSection()
        }
        val summary = data.session.aiSummary
        if (!summary.isNullOrBlank()) {
            page.heading("AI Analysis")
            page.wrappedBody(summary)
            page.advanceSection()
        }
        page.footer("Generated by MT_SW")
        return page.finish()
    }
}

/** Lays the lines out on pages and writes them as a PDF 1.4 file (one byte per character, so offsets are exact). */
private class PdfPages {
    private class Page(val content: StringBuilder = StringBuilder())

    private val pages = ArrayList<Page>()
    private var current: Page? = null
    private var y = MARGIN_TOP

    private fun ensure(): Page {
        current?.let {
            return it
        }
        return Page().also {
            pages.add(it)
            current = it
            y = MARGIN_TOP
        }
    }

    private fun breakIfNeeded(lines: Int = 1) {
        if (y + lines * LINE_HEIGHT > PAGE_HEIGHT - PAGE_BOTTOM_MARGIN) {
            current = null
            ensure()
        }
    }

    private fun text(page: Page, text: String, x: Float, top: Float, size: Float, bold: Boolean, gray: Float) {
        // The PDF's origin is the lower left corner, the layout counts from the top.
        page.content
            .append("BT ")
            .append(gray).append(" g /").append(if (bold) "F2 " else "F1 ").append(size).append(" Tf ")
            .append(x).append(' ').append(PAGE_HEIGHT - top).append(" Td (")
            .append(escape(text)).append(") Tj ET\n")
    }

    fun title(t: String) = ensure().let { text(it, t, MARGIN_LEFT, y, TITLE_SIZE, true, 0f); y += LINE_HEIGHT + SECTION_GAP }

    fun heading(t: String) {
        breakIfNeeded(2)
        text(ensure(), t, MARGIN_LEFT, y, HEADING_SIZE, true, 0f)
        y += LINE_HEIGHT
    }

    fun subheading(t: String) {
        breakIfNeeded()
        text(ensure(), t, MARGIN_LEFT, y, BODY_SIZE, true, 0f)
        y += LINE_HEIGHT
    }

    fun body(t: String) {
        breakIfNeeded()
        text(ensure(), t, MARGIN_LEFT, y, BODY_SIZE, false, 0f)
        y += LINE_HEIGHT
    }

    fun labelValue(label: String, value: String) {
        breakIfNeeded()
        val page = ensure()
        text(page, "$label:", MARGIN_LEFT, y, LABEL_SIZE, false, 0.3f)
        text(page, value, MARGIN_LEFT + LABEL_COLUMN_WIDTH, y, BODY_SIZE, false, 0f)
        y += LINE_HEIGHT
    }

    fun wrappedBody(t: String) {
        val maxChars = ((PAGE_WIDTH - MARGIN_LEFT * 2) / (BODY_SIZE * AVERAGE_CHAR_WIDTH)).toInt()
        var line = StringBuilder()
        for (paragraph in t.split("\n")) {
            for (word in paragraph.split(" ")) {
                if (line.isNotEmpty() && line.length + 1 + word.length > maxChars) {
                    body(line.toString())
                    line = StringBuilder(word)
                } else {
                    if (line.isNotEmpty()) line.append(' ')
                    line.append(word)
                }
            }
            if (line.isNotEmpty()) body(line.toString())
            line = StringBuilder()
        }
    }

    fun footer(t: String) {
        text(ensure(), t, MARGIN_LEFT, PAGE_HEIGHT - MARGIN_TOP / 2, FOOTER_SIZE, false, 0.5f)
    }

    fun advanceLine() {
        y += LINE_HEIGHT
    }

    fun advanceSection() {
        y += SECTION_GAP
    }

    fun finish(): ByteArray {
        ensure()
        // Objects: 1 catalog, 2 page list, 3 and 4 fonts, then a page and its content for every page.
        val out = StringBuilder("%PDF-1.4\n")
        val offsets = ArrayList<Int>()
        fun obj(body: String) {
            offsets.add(out.length)
            out.append(offsets.size).append(" 0 obj\n").append(body).append("\nendobj\n")
        }
        val pageIds = pages.indices.map { 5 + it * 2 }
        obj("<< /Type /Catalog /Pages 2 0 R >>")
        obj("<< /Type /Pages /Kids [" + pageIds.joinToString(" ") { "$it 0 R" } + "] /Count ${pages.size} >>")
        obj("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
        obj("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
        for ((i, page) in pages.withIndex()) {
            obj(
                "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 $PAGE_WIDTH $PAGE_HEIGHT] " +
                    "/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${pageIds[i] + 1} 0 R >>",
            )
            obj("<< /Length ${page.content.length} >>\nstream\n${page.content}endstream")
        }
        val xref = out.length
        out.append("xref\n0 ${offsets.size + 1}\n0000000000 65535 f \n")
        for (o in offsets) out.append(o.toString().padStart(10, '0')).append(" 00000 n \n")
        out.append("trailer\n<< /Size ${offsets.size + 1} /Root 1 0 R >>\nstartxref\n$xref\n%%EOF\n")
        return ByteArray(out.length) { out[it].code.toByte() }
    }

    private fun escape(text: String): String = buildString {
        for (c in text) {
            val ch = fold(c)
            when {
                ch == '(' || ch == ')' || ch == '\\' -> append('\\').append(ch)
                ch.code in 32..126 -> append(ch)
                ch.code in 160..255 -> append('\\').append(ch.code.toString(8).padStart(3, '0'))
                else -> append('?')
            }
        }
    }

    /** Letters the standard font has not got, written without their accents. */
    private fun fold(c: Char): Char = when (c) {
        'ą' -> 'a'
        'ć' -> 'c'
        'ę' -> 'e'
        'ł' -> 'l'
        'ń' -> 'n'
        'ś' -> 's'
        'ź', 'ż' -> 'z'
        'Ą' -> 'A'
        'Ć' -> 'C'
        'Ę' -> 'E'
        'Ł' -> 'L'
        'Ń' -> 'N'
        'Ś' -> 'S'
        'Ź', 'Ż' -> 'Z'
        else -> c
    }
}
