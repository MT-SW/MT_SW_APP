@file:Suppress("MagicNumber")

package org.meshtastic.core.ui.component

import androidx.compose.ui.Modifier
import androidx.compose.ui.input.pointer.PointerEventPass
import androidx.compose.ui.input.pointer.PointerEventType
import androidx.compose.ui.input.pointer.isSecondaryPressed
import androidx.compose.ui.input.pointer.pointerInput

/**
 * MT_SW: on the computer the right mouse button does the same as a long press (opens the extra menu), so the button
 * does not have to be held down. The press is consumed, so it does not also count as a normal click.
 */
fun Modifier.onRightClick(action: (() -> Unit)?): Modifier = if (action == null) {
    this
} else {
    pointerInput(action) {
        awaitPointerEventScope {
            while (true) {
                val event = awaitPointerEvent(PointerEventPass.Initial)
                if (event.type == PointerEventType.Press && event.buttons.isSecondaryPressed) {
                    event.changes.forEach { it.consume() }
                    action()
                }
            }
        }
    }
}
